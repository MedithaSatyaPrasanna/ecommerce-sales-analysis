-- ============================================================
-- SECTION 3: TOTAL REVENUE
-- Calculate total sales revenue across all order items.
-- Revenue = product price multiplied by quantity.
-- ============================================================

SELECT
    SUM(p.price * oi.quantity) AS total_revenue
FROM order_items AS oi
JOIN products AS p
    ON oi.product_id = p.product_id;


-- ============================================================
-- SECTION 4: REVENUE BY PRODUCT
-- Find the revenue generated by each product.
-- Show the highest-revenue product first.
-- ============================================================

SELECT
    p.product_name,
    SUM(p.price * oi.quantity) AS product_revenue
FROM order_items AS oi
JOIN products AS p
    ON oi.product_id = p.product_id
GROUP BY p.product_id, p.product_name
ORDER BY product_revenue DESC;


-- ============================================================
-- SECTION 5: REVENUE BY CUSTOMER
-- Calculate each customer's total spending.
-- Join customers, orders, order items, and products.
-- ============================================================

SELECT
    c.customer_name,
    SUM(p.price * oi.quantity) AS total_spent
FROM customers AS c
JOIN orders AS o
    ON c.customer_id = o.customer_id
JOIN order_items AS oi
    ON o.order_id = oi.order_id
JOIN products AS p
    ON oi.product_id = p.product_id
GROUP BY c.customer_id, c.customer_name
ORDER BY total_spent DESC;


-- ============================================================
-- SECTION 6: CUSTOMERS WITHOUT ORDERS
-- LEFT JOIN keeps customers even if they have no orders.
-- A NULL order_id identifies a customer without an order.
-- ============================================================

SELECT
    c.customer_id,
    c.customer_name,
    o.order_id
FROM customers AS c
LEFT JOIN orders AS o
    ON c.customer_id = o.customer_id
WHERE o.order_id IS NULL;


-- ============================================================
-- SECTION 7: MONTHLY REVENUE
-- Group sales by year and month.
-- DATE_FORMAT converts the order date to YYYY-MM format.
-- ============================================================

SELECT
    DATE_FORMAT(o.order_date, '%Y-%m') AS sales_month,
    SUM(p.price * oi.quantity) AS monthly_revenue
FROM orders AS o
JOIN order_items AS oi
    ON o.order_id = oi.order_id
JOIN products AS p
    ON oi.product_id = p.product_id
GROUP BY DATE_FORMAT(o.order_date, '%Y-%m')
ORDER BY sales_month;


-- ============================================================
-- SECTION 8: MONTHLY REVENUE PERCENTAGE
-- Calculate each month's share of total revenue.
-- ROUND(..., 2) displays two decimal places.
-- ============================================================

SELECT
    DATE_FORMAT(o.order_date, '%Y-%m') AS sales_month,
    SUM(p.price * oi.quantity) AS monthly_revenue,
    ROUND(
        SUM(p.price * oi.quantity) * 100.0 /
        (
            SELECT SUM(p2.price * oi2.quantity)
            FROM order_items AS oi2
            JOIN products AS p2
                ON oi2.product_id = p2.product_id
        ),
        2
    ) AS revenue_percentage
FROM orders AS o
JOIN order_items AS oi
    ON o.order_id = oi.order_id
JOIN products AS p
    ON oi.product_id = p.product_id
GROUP BY DATE_FORMAT(o.order_date, '%Y-%m')
ORDER BY sales_month;


-- ============================================================
-- SECTION 9: UNITS SOLD BY PRODUCT
-- Add up the quantity sold for each product.
-- This measures units, not revenue.
-- ============================================================

SELECT
    p.product_name,
    SUM(oi.quantity) AS units_sold
FROM products AS p
JOIN order_items AS oi
    ON p.product_id = oi.product_id
GROUP BY p.product_id, p.product_name
ORDER BY units_sold DESC;


-- ============================================================
-- SECTION 10: REVENUE BY CATEGORY
-- Calculate total revenue for each product category.
-- ============================================================

SELECT
    p.category,
    SUM(p.price * oi.quantity) AS category_revenue
FROM products AS p
JOIN order_items AS oi
    ON p.product_id = oi.product_id
GROUP BY p.category
ORDER BY category_revenue DESC;


-- ============================================================
-- SECTION 11: AVERAGE ORDER VALUE
-- First calculate the total value of each order.
-- Then average the order totals.
-- ============================================================

SELECT
    ROUND(AVG(order_revenue), 2) AS average_order_value
FROM (
    SELECT
        o.order_id,
        SUM(p.price * oi.quantity) AS order_revenue
    FROM orders AS o
    JOIN order_items AS oi
        ON o.order_id = oi.order_id
    JOIN products AS p
        ON oi.product_id = p.product_id
    GROUP BY o.order_id
) AS order_totals;


-- ============================================================
-- SECTION 12: MONTH-OVER-MONTH REVENUE CHANGE
-- A CTE stores monthly revenue temporarily for this query.
-- LAG() retrieves the previous month's revenue.
-- Revenue change = current month minus previous month.
-- Requires a MySQL version supporting CTEs and window functions.
-- ============================================================

WITH monthly_sales AS (
    SELECT
        DATE_FORMAT(o.order_date, '%Y-%m') AS sales_month,
        SUM(p.price * oi.quantity) AS monthly_revenue
    FROM orders AS o
    JOIN order_items AS oi
        ON o.order_id = oi.order_id
    JOIN products AS p
        ON oi.product_id = p.product_id
    GROUP BY DATE_FORMAT(o.order_date, '%Y-%m')
)
SELECT
    sales_month,
    monthly_revenue,

    -- Retrieve the previous month's revenue.
    LAG(monthly_revenue) OVER (
        ORDER BY sales_month
    ) AS previous_month_revenue,

    -- Calculate the difference between the two months.
    monthly_revenue -
        LAG(monthly_revenue) OVER (
            ORDER BY sales_month
        ) AS revenue_change

FROM monthly_sales
ORDER BY sales_month;


-- ============================================================
-- SECTION 13: CHECK FOR MISSING CUSTOMER INFORMATION
-- Find customers whose name or city is missing.
-- No returned rows means no missing values were found here.
-- ============================================================

SELECT *
FROM customers
WHERE customer_name IS NULL
   OR city IS NULL;


-- ============================================================
-- SECTION 14: CHECK INVALID ORDER QUANTITIES
-- Find order items with missing, zero, or negative quantities.
-- ============================================================

SELECT *
FROM order_items
WHERE quantity IS NULL
   OR quantity <= 0;


